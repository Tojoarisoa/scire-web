// Bundles src/entry.js (the model wrapper, and the worker that runs it: one file) with WebLLM into ../dist/offline-model.js, and
// writes the licenses of what it contains. Run: npm run build
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.join(here, "..", "dist");
fs.mkdirSync(out, { recursive: true });

const names = new Set();
for (const [entry, file] of [["src/entry.js", "offline-model.js"]]) {
  const result = await build({
    entryPoints: [path.join(here, entry)], bundle: true, minify: true, format: "esm", target: "es2022", legalComments: "none",
    banner: { js: "/* SCIRE on-device model: WebLLM (Apache-2.0). Licenses: THIRD-PARTY-LICENSES-offline-model.txt (served at /assets/THIRD-PARTY-LICENSES-offline-model.txt). */" },
    metafile: true, outfile: path.join(out, file),
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    const at = input.lastIndexOf("node_modules/");
    if (at < 0) continue;
    const parts = input.slice(at + "node_modules/".length).split("/");
    names.add(parts[0].startsWith("@") ? parts.slice(0, 2).join("/") : parts[0]);
  }
  console.log(`${file}: ${(fs.statSync(path.join(out, file)).size / 1024).toFixed(0)} kb`);
}

const licenseFile = (dir) => fs.readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(f));
const blocks = [];
for (const name of [...names].sort()) {
  const dir = path.join(here, "node_modules", name);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const file = licenseFile(dir);
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository && pkg.repository.url || pkg.homepage || "";
  if (!file) throw new Error(`${name} has no license file; add its notice by hand before shipping it`);
  blocks.push(`${"=".repeat(78)}\n${pkg.name}@${pkg.version}  (${pkg.license})\n${repo.replace(/^git\+/, "")}\n${"=".repeat(78)}\n\n${fs.readFileSync(path.join(dir, file), "utf8").trim()}\n`);
}
const header = `Third-party software included in offline-model.js

The optional on-device language model of SCIRE bundles the packages below, each under its own license, reproduced in full.
The model weights it downloads (Meta Llama 3.2, from the MLC project's Hugging Face pages) are under the Llama 3.2 Community
License, https://www.llama.com/llama3_2/license/ , which the learner is shown before the download.
Generated by \`npm run build\` (offline-model/build.mjs).

`;
fs.writeFileSync(path.join(out, "THIRD-PARTY-LICENSES-offline-model.txt"), header + blocks.join("\n"));
console.log(`licenses for ${names.size} packages`);
