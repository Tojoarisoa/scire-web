// Bundles src/index.jsx (React, React Flow and our map code) into ../dist/knowledge-map.js and writes
// ../dist/THIRD-PARTY-LICENSES.txt from the packages the bundle really contains. Run: npm run build
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.join(here, "..", "dist");
fs.mkdirSync(out, { recursive: true });

const result = await build({
  entryPoints: [path.join(here, "src/index.jsx")],
  bundle: true, minify: true, format: "iife", globalName: "TutorMapLib", loader: { ".css": "text" },
  define: { "process.env.NODE_ENV": '"production"' }, target: "es2020", legalComments: "none",
  banner: { js: "/* SCIRE knowledge map. Bundles React, React Flow and their dependencies (MIT, ISC, BSD-3-Clause); their licenses: THIRD-PARTY-LICENSES.txt (served at /assets/THIRD-PARTY-LICENSES.txt). */" },
  metafile: true, outfile: path.join(out, "knowledge-map.js"),
});

const names = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const at = input.lastIndexOf("node_modules/");
  if (at < 0) continue;
  const parts = input.slice(at + "node_modules/".length).split("/");
  names.add(parts[0].startsWith("@") ? parts.slice(0, 2).join("/") : parts[0]);
}

const licenseFile = (dir) => fs.readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(f));
const blocks = [];
for (const name of [...names].sort()) {
  const dir = path.join(here, "node_modules", name);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const file = licenseFile(dir);
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository && pkg.repository.url || pkg.homepage || "";
  if (!file) throw new Error(`${name} has no license file; add its notice by hand before shipping it`);
  blocks.push(`${"=".repeat(78)}\n${pkg.name}@${pkg.version}  (${pkg.license})\n${repo.replace(/^git\+/, "")}\n${"=".repeat(78)}\n\n${fs.readFileSync(path.join(dir, file), "utf8").trim()}\n`);
}
const header = `Third-party software included in knowledge-map.js

The SCIRE knowledge map bundles the packages below. Each is used under its own license, reproduced in full.
This file is generated by \`npm run build\` (knowledge-map/build.mjs) from the packages the bundle
actually contains.

`;
fs.writeFileSync(path.join(out, "THIRD-PARTY-LICENSES.txt"), header + blocks.join("\n"));
console.log(`bundle: ${(fs.statSync(path.join(out, "knowledge-map.js")).size / 1024).toFixed(1)} kb, licenses for ${names.size} packages`);
